import express, { Router } from "express";
import { describe, it, expect } from "vitest";
import { discoverRoutes, mergeDiscoveredPaths, mergePrismaSchemas } from "./openapiDiscovery.js";

describe("OpenAPI discovery", () => {
  const app = express();
  const rides = Router();
  rides.get("/", (_q, r) => r.end());
  rides.post("/:id/join", (_q, r) => r.end());
  const nested = Router({ mergeParams: true });
  nested.delete("/:memberId", (_q, r) => r.end());
  rides.use("/:id/members", nested);
  app.use("/api/rides", rides);
  app.get("/health", (_q, r) => r.end());

  it("finds mounted routes including params and nested routers", () => {
    const found = discoverRoutes(app).map((r) => `${r.method} ${r.path}`).sort();
    expect(found).toEqual([
      "delete /api/rides/{id}/members/{memberId}",
      "get /api/rides",
      "get /health",
      "post /api/rides/{id}/join",
    ]);
  });

  it("adds stubs only for operations the JSDoc spec lacks", () => {
    const spec: any = { paths: { "/api/rides": { get: { summary: "List rides" } } } };
    const added = mergeDiscoveredPaths(spec, discoverRoutes(app));
    expect(added).toBe(3);
    expect(spec.paths["/api/rides"].get.summary).toBe("List rides");
    expect(spec.paths["/api/rides/{id}/join"].post["x-autogenerated"]).toBe(true);
    expect(spec.paths["/api/rides/{id}/join"].post.parameters[0].name).toBe("id");
    expect(spec.tags.map((t: any) => t.name)).toContain("Rides");
  });

  it("derives schemas from Prisma and never exposes credential columns", () => {
    const spec: any = {};
    mergePrismaSchemas(spec);
    expect(spec.components.schemas.Ride.properties.title).toEqual({ type: "string" });
    expect(spec.components.schemas.Ride.properties.description).toEqual({ type: "string", nullable: true });
    expect(spec.components.schemas.Ride.required).toContain("title");
    expect(spec.components.schemas.RideStatus.enum).toContain("PLANNED");
    expect(spec.components.schemas.Account).toBeUndefined();
    const all = JSON.stringify(spec.components.schemas);
    expect(all).not.toMatch(/"password"|"accessToken"|"refreshToken"/);
  });
});
