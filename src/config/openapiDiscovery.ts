import type { Express } from "express";
import { readFileSync } from "node:fs";
import path from "node:path";
import { Prisma } from "@prisma/client";

/**
 * The hand-written `@swagger` JSDoc blocks give rich docs for some routes, but
 * nothing forces them to be written or kept current. This module closes the gap
 * by reading what the server actually serves, so a new route or schema shows up
 * in the reference automatically:
 *
 *  - every mounted Express route becomes an operation (stub if no JSDoc exists)
 *  - every Prisma model and enum becomes a component schema
 *
 * JSDoc stays authoritative: discovery only fills in what it did not describe.
 */

const HTTP_METHODS = ["get", "post", "put", "patch", "delete"] as const;
type HttpMethod = (typeof HTTP_METHODS)[number];

export interface DiscoveredRoute {
  method: HttpMethod;
  path: string; // OpenAPI style: /api/rides/{id}
}

// Express 4 keeps a mounted path only as a regexp; turn it back into a string.
function layerPath(layer: any): string {
  if (layer.regexp?.fast_slash) return "";
  let keyIndex = 0;
  const source: string = layer.regexp?.source ?? "";
  return source
    .replace(/^\^/, "")
    .replace(/\\\/\?\(\?=\\\/\|\$\)$/, "")
    .replace(/\\\/\?$/, "")
    .replace(/\$$/, "")
    .replace(/\(\?:\\\/\(\[\^\\?\/\]\+\?\)\)/g, () => `/{${layer.keys?.[keyIndex++]?.name ?? "param"}}`)
    .replace(/\\\//g, "/")
    .replace(/\\(.)/g, "$1");
}

function normalise(p: string): string {
  const cleaned = p.replace(/\/{2,}/g, "/").replace(/(.)\/$/, "$1");
  return cleaned || "/";
}

function walk(stack: any[], prefix: string, out: DiscoveredRoute[]): void {
  for (const layer of stack) {
    if (layer.route) {
      const routePath = String(layer.route.path ?? "").replace(/:([A-Za-z0-9_]+)\??/g, "{$1}");
      for (const method of HTTP_METHODS) {
        if (layer.route.methods?.[method]) {
          out.push({ method, path: normalise(prefix + routePath) });
        }
      }
    } else if (layer.handle?.stack) {
      walk(layer.handle.stack, prefix + layerPath(layer), out);
    }
  }
}

export function discoverRoutes(app: Express): DiscoveredRoute[] {
  const stack = (app as any)._router?.stack ?? (app as any).router?.stack ?? [];
  const out: DiscoveredRoute[] = [];
  walk(stack, "", out);
  return out;
}

const SKIP = [/^\/api-docs/, /^\/redoc/, /^\/$/, /^\/metrics$/];

function tagFor(path: string): string {
  const parts = path.split("/").filter(Boolean);
  const seg = parts[0] === "api" ? parts[1] : parts[0];
  if (!seg || seg.startsWith("{")) return "Other";
  return seg.replace(/-/g, " ").replace(/^./, (c) => c.toUpperCase());
}

/** Adds a stub operation for every served route the JSDoc did not describe. */
export function mergeDiscoveredPaths(spec: any, routes: DiscoveredRoute[]): number {
  spec.paths ??= {};
  const known = new Set(
    Object.keys(spec.paths).flatMap((p) =>
      Object.keys(spec.paths[p]).map((m) => `${m.toLowerCase()} ${normalise(p)}`),
    ),
  );
  let added = 0;
  for (const { method, path } of routes) {
    if (SKIP.some((re) => re.test(path)) || known.has(`${method} ${path}`)) continue;
    const params = [...path.matchAll(/\{([^}]+)\}/g)].map((m) => ({
      name: m[1],
      in: "path",
      required: true,
      schema: { type: "string" },
    }));
    spec.paths[path] ??= {};
    spec.paths[path][method] = {
      tags: [tagFor(path)],
      summary: `${method.toUpperCase()} ${path}`,
      description:
        "Autogenerated from the running server. No detailed documentation has been written for this route yet.",
      ...(params.length ? { parameters: params } : {}),
      responses: { "200": { description: "Success" } },
      "x-autogenerated": true,
    };
    known.add(`${method} ${path}`);
    added++;
  }

  const tagged = new Set((spec.tags ?? []).map((t: any) => t.name));
  for (const item of Object.values<any>(spec.paths)) {
    for (const op of Object.values<any>(item)) {
      for (const t of op?.tags ?? []) {
        if (!tagged.has(t)) {
          (spec.tags ??= []).push({ name: t });
          tagged.add(t);
        }
      }
    }
  }
  return added;
}

// Auth bookkeeping tables and credential-like columns are never documented.
const HIDDEN_MODELS =
  /^(Account|Session|Verification|Passkey|AccountSecurityEvent|AccountRecoveryRequest|AccountRecoveryChallenge)$/i;
const HIDDEN_FIELDS = /password|secret|hash|token|receipt/i;

const SCALAR: Record<string, any> = {
  String: { type: "string" },
  Boolean: { type: "boolean" },
  Int: { type: "integer" },
  BigInt: { type: "integer", format: "int64" },
  Float: { type: "number" },
  Decimal: { type: "number" },
  DateTime: { type: "string", format: "date-time" },
  Json: {},
  Bytes: { type: "string", format: "byte" },
};

// Prisma 7's runtime DMMF omits optionality and list flags, so read them from the
// schema file when it ships with the deployment (it does: migrate deploy needs it).
function readFieldShapes(): Map<string, { optional: boolean; list: boolean }> {
  const shapes = new Map<string, { optional: boolean; list: boolean }>();
  try {
    const text = readFileSync(path.resolve(process.cwd(), "prisma/schema.prisma"), "utf8");
    for (const block of text.matchAll(/^model\s+(\w+)\s*\{([\s\S]*?)^\}/gm)) {
      for (const line of block[2].split(/\r?\n/)) {
        const m = line.match(/^\s*(\w+)\s+\w+(\?|\[\])?/);
        if (m && !line.trim().startsWith("//") && !line.trim().startsWith("@@")) {
          shapes.set(`${block[1]}.${m[1]}`, { optional: m[2] === "?", list: m[2] === "[]" });
        }
      }
    }
  } catch {
    // No schema file: fall back to documenting fields as required scalars.
  }
  return shapes;
}

function readEnums(): Map<string, string[]> {
  const enums = new Map<string, string[]>();
  try {
    const text = readFileSync(path.resolve(process.cwd(), "prisma/schema.prisma"), "utf8");
    for (const block of text.matchAll(/^enum\s+(\w+)\s*\{([\s\S]*?)^\}/gm)) {
      const values = block[2]
        .split(/\r?\n/)
        .map((l) => l.trim())
        .filter((l) => l && !l.startsWith("//") && !l.startsWith("@@"))
        .map((l) => l.split(/\s+/)[0]);
      enums.set(block[1], values);
    }
  } catch {
    // No schema file: enums are left undocumented.
  }
  return enums;
}

/** Adds a component schema for every Prisma model and enum not already defined. */
export function mergePrismaSchemas(spec: any): number {
  const dmmf = (Prisma as any).dmmf?.datamodel;
  if (!dmmf) return 0;
  const schemas = ((spec.components ??= {}).schemas ??= {});
  const shapes = readFieldShapes();
  const enums = readEnums();
  let added = 0;

  for (const [name, values] of enums) {
    if (schemas[name]) continue;
    schemas[name] = { type: "string", enum: values };
    added++;
  }
  for (const m of dmmf.models ?? []) {
    if (schemas[m.name] || HIDDEN_MODELS.test(m.name)) continue;
    const properties: Record<string, any> = {};
    const required: string[] = [];
    for (const f of m.fields) {
      if (f.kind === "object" || HIDDEN_FIELDS.test(f.name)) continue;
      let schema: any =
        enums.has(f.type) ? { $ref: `#/components/schemas/${f.type}` } : { ...(SCALAR[f.type] ?? {}) };
      const shape = shapes.get(`${m.name}.${f.name}`) ?? { optional: false, list: false };
      if (shape.list) schema = { type: "array", items: schema };
      if (shape.optional) schema = { ...schema, nullable: true };
      properties[f.name] = schema;
      if (!shape.optional && !shape.list) required.push(f.name);
    }
    schemas[m.name] = { type: "object", properties, ...(required.length ? { required } : {}) };
    added++;
  }
  return added;
}
