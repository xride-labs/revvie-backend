/** Lowercase + trim. Returns "" for non-strings. */
export function normalizeEmail(email: unknown): string {
  return typeof email === "string" ? email.trim().toLowerCase() : "";
}

/** Extract the domain part of an email, or null if malformed. */
export function getEmailDomain(email: unknown): string | null {
  const normalized = normalizeEmail(email);
  const at = normalized.lastIndexOf("@");
  if (at <= 0 || at === normalized.length - 1) return null;
  const domain = normalized.slice(at + 1);
  // Basic sanity: must contain a dot and no spaces/commas
  if (!domain.includes(".") || /[\s,;]/.test(domain)) return null;
  return domain;
}

/**
 * True when the email belongs to a known disposable / throwaway service.
 * Subdomains of a blocked domain count as disposable too.
 * Malformed emails return false here (format validation lives in Zod).
 */
export function isDisposableEmail(email: unknown): boolean {
  const domain = getEmailDomain(email);
  if (!domain) return false;
  if (BLOCKED_DOMAINS.has(domain)) return true;
  for (const blocked of BLOCKED_DOMAINS) {
    if (domain.endsWith(`.${blocked}`)) return true;
  }
  return false;
}

/** Shared rejection message so API + validators stay consistent. */
export const DISPOSABLE_EMAIL_MESSAGE =
  "Please use a permanent email address. Disposable or temporary email addresses are not allowed.";

export function assertCredibleEmail(email: unknown): void {
  if (isDisposableEmail(email)) {
    throw new Error(DISPOSABLE_EMAIL_MESSAGE);
  }
}
